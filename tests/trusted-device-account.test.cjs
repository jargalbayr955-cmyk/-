const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = file => fs.readFileSync(path.join(__dirname, '..', file), 'utf8')

test('customer trusted device restores session automatically but deliberate logout can suppress auto restore', () => {
  const device = read('lib/server/device-session.ts')
  const session = read('app/api/customer/session/route.ts')
  const client = read('lib/client/session.ts')
  const logout = read('app/api/customer/logout/route.ts')
  assert.match(device, /CUSTOMER_TRUST_COOKIE = 'achilt_customer_trust'/)
  assert.match(session, /readTrustedCustomerDevice\(req\)/)
  assert.match(session, /setDeviceSession\(res, user\.id, 'customer'\)/)
  assert.match(session, /searchParams\.get\('restore'\) !== '0'/)
  assert.match(client, /CUSTOMER_RESTORE_BLOCK_STORAGE_KEY/)
  assert.match(client, /\/api\/customer\/session\?restore=0/)
  assert.match(client, /sessionStorage\.setItem\(CUSTOMER_RESTORE_BLOCK_STORAGE_KEY, '1'\)/)
  assert.doesNotMatch(logout, /achilt_customer_trust[^\n]*maxAge:\s*0/)
})

test('customer header is a profile button with phone, completed service history and app logout inside', () => {
  const account = read('app/components/customer-account.tsx')
  const history = read('app/api/customer/history/route.ts')
  assert.match(account, /👤/)
  assert.match(account, />Хэрэглэгч</)
  assert.doesNotMatch(account, /Нэвтэрсэн дугаар/)
  assert.match(account, /Өмнө авсан үйлчилгээ/)
  assert.match(account, /Апп-аас гарах/)
  assert.match(account, /\/api\/customer\/history/)
  assert.match(history, /requireCustomer\(req\)/)
  assert.match(history, /\.eq\('user_id', user\.id\)/)
  assert.match(history, /\.eq\('status', 'completed'\)/)
  assert.doesNotMatch(history, /searchParams.*user_id|body.*user_id/)
})

test('driver remembered device is version-bound, restored on reopen and cleared only by explicit driver logout', () => {
  const device = read('lib/server/device-session.ts')
  const login = read('app/api/driver/login/route.ts')
  const register = read('app/api/driver/register/request/route.ts')
  const session = read('app/api/driver/session/route.ts')
  const logout = read('app/api/driver/logout/route.ts')
  assert.match(device, /DRIVER_TRUST_COOKIE = 'achilt_driver_trust'/)
  assert.match(device, /signSession\(id, 'driver', version\)/)
  assert.match(login, /setTrustedDriverDevice\(res, data\.id, session_version\)/)
  assert.match(register, /setTrustedDriverDevice\(response, driver\.id, session_version\)/)
  assert.match(session, /readTrustedDriverDevice\(req\)/)
  assert.match(session, /data\.session_version !== trusted\.version/)
  assert.match(session, /setDeviceSession\(res, driver\.id, 'driver', restoredVersion\)/)
  assert.match(logout, /clearTrustedDriverDevice\(res\)/)
})
