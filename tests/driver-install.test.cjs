const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const read = file => fs.readFileSync(path.join(__dirname, '..', file), 'utf8')

test('installed driver PWA opens on the driver registration and login route', () => {
  const manifest = JSON.parse(read('public/driver-manifest.json'))
  const layout = read('app/driver/layout.tsx')
  assert.equal(manifest.id, '/driver')
  assert.equal(manifest.start_url, '/driver')
  assert.equal(manifest.display, 'standalone')
  assert.match(layout, /manifest:\s*['"]\/driver-manifest\.json['"]/)
  assert.match(layout, /DriverInstallButton/)
})

test('driver install control sits below login and supports native browser install prompt', () => {
  const source = read('app/components/driver-install-button.tsx')
  assert.match(source, /beforeinstallprompt/)
  assert.match(source, /installPrompt\.prompt\(\)/)
  assert.match(source, /insertAdjacentElement\(['"]afterend['"]/)
  assert.match(source, /Жолооч апп утас дээр суулгах/)
  assert.match(source, /navigator\.serviceWorker\.register\(['"]\/sw\.js['"]\)/)
  assert.match(source, /Add to Home Screen/)
  assert.match(source, /browserStandaloneMode\(\)/)
  assert.match(source, /a\[href=\"\/driver\/app\"\]/)
})

test('main customer login can install the driver PWA while standalone mode hides duplicate install controls', () => {
  const start = read('app/start/page.tsx')
  const startLayout = read('app/start/layout.tsx')
  const entry = read('app/components/driver-install-entry-link.tsx')
  assert.match(start, /DriverInstallEntryLink/)
  assert.match(startLayout, /manifest:\s*['"]\/driver-manifest\.json['"]/)
  assert.match(entry, /button\.auth-submit/)
  assert.match(entry, /insertAdjacentElement\(['"]afterend['"]/)
  assert.match(entry, /beforeinstallprompt/)
  assert.match(entry, /installPrompt\.prompt\(\)/)
  assert.match(entry, /navigator\.serviceWorker\.register\(['"]\/sw\.js['"]\)/)
  assert.match(entry, /Жолооч апп утас дээр суулгах/)
  assert.match(entry, /browserStandaloneMode\(\)/)
  assert.match(entry, /if \(!target \|\| installed\) return null/)
})

test('notification click navigates an already-open driver window to the notification target', () => {
  const worker = read('public/sw.js')
  assert.match(worker, /client\.navigate\(fullUrl\)/)
  assert.match(worker, /clients\.openWindow\(fullUrl\)/)
})
