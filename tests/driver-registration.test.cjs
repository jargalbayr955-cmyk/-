test('payment webhook reserves 0xxxxx for new registrations, keeps commissions nonzero-prefixed and accepts legacy eight-digit registrations', () => {
  const parser = read('lib/server/khan-bank-sms.ts')
  const webhook = read('lib/server/payment-webhook.ts')
  const route = read('app/api/payment/verify/route.ts')
  assert.ok(webhook.includes('d{6}') && webhook.includes('d{8}'))
  assert.ok(parser.includes('Utga:') && parser.includes('{6}') && parser.includes('{8}'))
  assert.match(route, /\^0\\d\{5\}\$/)
  assert.match(route, /\^\[1-9\]\\d\{5\}\$/)
  assert.match(route, /confirm_driver_registration_payment_by_code/)
  assert.match(route, /confirm_driver_commission/)
  assert.match(route, /confirm_driver_registration_payment/)
})

test('registration migration locks the promo amount, activates paid drivers and permits one PIN setup', () => {
  const migration = read('supabase/migrations/20261028095500_v5_8_driver_registration_promo_self_pin.sql')
  assert.match(migration, /add column if not exists amount_due numeric/i)
  assert.match(migration, /add column if not exists pin_set_at timestamptz/i)
  assert.match(migration, /2026-11-11 09:55:00\+00/)
  assert.match(migration, /then 25000[\s\S]*else 100000/)
  assert.match(migration, /p_amount is distinct from v_request\.amount_due/)
  assert.match(migration, /false,[\s\n]*true,[\s\n]*gen_random_uuid\(\)/)
  assert.match(migration, /create or replace function public\.confirm_driver_registration_payment\(p_phone text,p_amount numeric\)/)
  assert.match(migration, /complete_driver_registration_pin/)
  assert.match(migration, /extensions\.crypt\(p_pin,extensions\.gen_salt\('bf',10\)\)/)
  assert.match(migration, /pin_set_at is not null/)
  assert.match(migration, /revoke all on function public\.complete_driver_registration_pin/)
})
