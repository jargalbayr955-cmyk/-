const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = file => fs.readFileSync(path.join(__dirname, '..', file), 'utf8')

test('driver registration is self-service, covers all six services and redirects straight to the driver map', () => {
  const auth = read('app/components/customer-auth.tsx')
  const entry = read('app/components/driver-registration-entry.tsx')
  const layout = read('app/driver/layout.tsx')
  const dialog = read('app/components/driver-registration.tsx')
  const services = read('lib/service-types.ts')
  assert.doesNotMatch(auth, /Жолоочоор бүртгүүлэх/)
  assert.doesNotMatch(auth, /DriverRegistrationDialog/)
  assert.match(entry, /Жолоочоор бүртгүүлэх/)
  assert.match(entry, /DriverRegistrationDialog/)
  assert.match(entry, /Нэвтрэх →/)
  assert.match(layout, /DriverRegistrationEntry/)
  assert.match(dialog, /type Step = 'choose-service' \| 'choose-tow' \| 'details'/)
  assert.doesNotMatch(dialog, /'payment'/)
  assert.match(dialog, /ServiceTypePicker/)
  for (const label of ['Ачилт', 'Кран', 'Экскаватор', 'Машин асаалт', 'Бобкат', 'Ковш']) assert.match(services, new RegExp(label))
  assert.match(dialog, /vehicle-buten-achigch-original\.svg/)
  assert.match(dialog, /vehicle-chiregch-original\.svg/)
  assert.match(dialog, /service_type: serviceType/)
  assert.match(dialog, /car_type: serviceType === 'achilt' \? carType : null/)
  assert.match(dialog, /Нэр/)
  assert.match(dialog, /Утасны дугаар/)
  assert.match(dialog, /Нэр, утасны дугаар байхад бүртгэл үүснэ/)
  assert.match(dialog, /Бүртгүүлээд шууд жолоочийн газрын зураг руу орно/)
  assert.match(dialog, /window\.location\.replace/)
  assert.match(dialog, /body\.redirect/)
  assert.match(dialog, /'\/driver'/)
  assert.doesNotMatch(dialog, /Машин \/ техникийн дугаар/)
  assert.doesNotMatch(dialog, /6 оронтой PIN/)
  assert.doesNotMatch(dialog, /REGISTRATION_FEE/)
  assert.doesNotMatch(dialog, /IBAN/)
  assert.doesNotMatch(dialog, /ГҮЙЛГЭЭНИЙ УТГА/)
  assert.doesNotMatch(dialog, /MacroDroid/)
})

test('self-registration creates an active working driver, sets a session cookie and requires no payment', () => {
  const request = read('app/api/driver/register/request/route.ts')
  const migration = read('supabase/migrations/20261029195500_driver_registration_direct_map.sql')
  const driverServer = read('lib/server/driver.ts')
  const serviceMigration = read('supabase/migrations/20261029043322_unified_service_types.sql')
  assert.match(request, /normalizeMnPhone/)
  assert.match(request, /isSessionConfigured/)
  assert.match(request, /start_driver_registration_v5/)
  assert.match(request, /p_service_type/)
  assert.match(request, /p_car_type/)
  assert.match(request, /p_name/)
  assert.doesNotMatch(request, /p_car_number/)
  assert.doesNotMatch(request, /p_photo_data_url/)
  assert.doesNotMatch(request, /p_pin/)
  assert.match(request, /setDeviceSession/)
  assert.match(request, /payment_required: false/)
  assert.match(request, /redirect: '\/driver'/)
  assert.match(migration, /start_driver_registration_v5/)
  assert.match(migration, /extensions\.crypt\('000000'/)
  assert.match(migration, /true,false,true,v_session_version/)
  assert.match(migration, /'payment_required',false/)
  assert.doesNotMatch(migration, /driver_registration_requests/)
  assert.match(migration, /grant execute on function public\.start_driver_registration_v5/)
  assert.match(driverServer, /Pick<DriverSessionRecord, 'name'>/)
  assert.doesNotMatch(driverServer, /const carNumber/)
  assert.doesNotMatch(driverServer, /!carNumber/)
  assert.match(serviceMigration, /service_type/)
  for (const id of ['achilt', 'crane', 'excavator', 'car_start', 'bobcat', 'loader']) assert.match(serviceMigration, new RegExp(id))
})

test('MacroDroid ignores registration references and only confirms driver commissions', () => {
  const parser = read('lib/server/khan-bank-sms.ts')
  const webhook = read('lib/server/payment-webhook.ts')
  const route = read('app/api/payment/verify/route.ts')
  assert.ok(webhook.includes('d{6}') && webhook.includes('d{8}'))
  assert.ok(parser.includes('Utga:') && parser.includes('{6}') && parser.includes('{8}'))
  assert.match(route, /\^0\\d\{5\}\$/)
  assert.match(route, /\^\\d\{8\}\$/)
  assert.match(route, /driver_registration_manual/)
  assert.match(route, /\^\[1-9\]\\d\{5\}\$/)
  assert.match(route, /confirm_driver_commission/)
  assert.doesNotMatch(route, /confirm_driver_registration_payment_by_code/)
  assert.doesNotMatch(route, /confirm_driver_registration_payment/)
})
