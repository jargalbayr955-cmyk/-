const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = file => fs.readFileSync(path.join(__dirname, '..', file), 'utf8')

test('customer login exposes paid driver registration with both tow types and requested bank details', () => {
  const auth = read('app/components/customer-auth.tsx')
  const dialog = read('app/components/driver-registration.tsx')
  assert.match(auth, /Жолоочоор бүртгүүлэх/)
  assert.match(auth, /DriverRegistrationDialog/)
  assert.match(dialog, /Бүтэн ачигч/)
  assert.match(dialog, /Чирэгч/)
  assert.match(dialog, /IBAN MN51 0005 00/)
  assert.match(dialog, /5736120860/)
  assert.match(dialog, /Т\.Жаргалбаяр/)
  assert.match(dialog, /Гүйлгээний утга/)
  assert.match(dialog, /Баталгаажуулах/)
  assert.match(dialog, /Тантай/)
})

test('driver registration APIs validate phone/type, rate limit requests and only report paid server state', () => {
  const request = read('app/api/driver/register/request/route.ts')
  const confirm = read('app/api/driver/register/confirm/route.ts')
  assert.match(request, /normalizeMnPhone/)
  assert.match(request, /start_driver_registration/)
  assert.match(request, /driver-register-phone/)
  assert.match(confirm, /get_driver_registration_status/)
  assert.match(confirm, /status === 'paid'/)
  assert.match(confirm, /awaiting_payment/)
})

test('payment webhook preserves six-digit commissions and accepts eight-digit registration phone references', () => {
  const parser = read('lib/server/khan-bank-sms.ts')
  const webhook = read('lib/server/payment-webhook.ts')
  const route = read('app/api/payment/verify/route.ts')
  assert.match(parser, /\\d\{6\}\|\\d\{8\}/)
  assert.match(webhook, /\\d\{6\}\|\\d\{8\}/)
  assert.match(route, /confirm_driver_commission/)
  assert.match(route, /confirm_driver_registration_payment/)
  assert.match(route, /\+976/)
})

test('registration migration is server-only and creates an inactive driver only after an incoming payment', () => {
  const sql = read('supabase/migrations/20261028_v5_8_driver_registration_payments.sql')
  assert.match(sql, /enable row level security/i)
  assert.match(sql, /revoke all on table public\.driver_registration_requests from public, anon, authenticated/i)
  assert.match(sql, /confirm_driver_registration_payment/)
  assert.match(sql, /values\(p_phone,'Шинэ жолооч',null,[\s\S]*false,false\)/)
  assert.match(sql, /payment_confirmed_at=now\(\)/)
})
