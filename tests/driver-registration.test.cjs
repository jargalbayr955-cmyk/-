test('self-registration activates the driver immediately with a private PIN and no admin approval gate', () => {
  const request = read('app/api/driver/register/request/route.ts')
  const migration = read('supabase/migrations/20261029075000_self_service_driver_registration.sql')
  const serviceMigration = read('supabase/migrations/20261029043322_unified_service_types.sql')
  assert.match(request, /normalizeMnPhone/)
  assert.match(request, /isServiceType/)
  assert.match(request, /start_driver_registration_v4/)
  assert.match(request, /p_service_type/)
  assert.match(request, /p_car_type/)
  assert.match(request, /p_name/)
  assert.match(request, /p_car_number/)
  assert.match(request, /p_pin/)
  assert.match(request, /p_photo_data_url/)
  assert.match(request, /pin !== '000000'/)
  assert.match(migration, /drop trigger if exists mark_manual_driver_registration_paid_on_activation/)
  assert.match(migration, /extensions\.crypt\(p_pin/)
  assert.match(migration, /car_number=v_car_number/)
  assert.match(migration, /active=true/)
  assert.match(migration, /false,false,true,pg_catalog\.gen_random_uuid\(\)/)
  assert.match(migration, /amount_due=25000/)
  assert.match(migration, /'approval_required',false/)
  assert.match(migration, /r\.status='awaiting_payment'/)
  assert.match(migration, /grant execute on function public\.start_driver_registration_v4/)
  assert.match(serviceMigration, /service_type/)
  for (const id of ['achilt', 'crane', 'excavator', 'car_start', 'bobcat', 'loader']) assert.match(serviceMigration, new RegExp(id))
})

test('MacroDroid ignores registration references and only confirms driver commissions', () => {
  const parser = read('lib/server/khan-bank-sms.ts')
  const webhook = read('lib/server/payment-webhook.ts')
  const route = read('app/api/payment/verify/route.ts')
  assert.ok(webhook.includes('d{6}') && webhook.includes('d{8}'))
  assert.ok(parser.includes('Utga:') && parser.includes('{6}') && parser.includes('{8}'))
  assert.match(route, /\^0\\d\{5\}\$/)
  assert.match(route, /\^\\d\{8\}\$/)
  assert.match(route, /driver_registration_manual/)
  assert.match(route, /\^\[1-9\]\\d\{5\}\$/)
  assert.match(route, /confirm_driver_commission/)
  assert.doesNotMatch(route, /confirm_driver_registration_payment_by_code/)
  assert.doesNotMatch(route, /confirm_driver_registration_payment/)
})
